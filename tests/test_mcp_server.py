class TestHandoverReverseTool:
    """Unit tests for handover_reverse_impl (mocks reverse + discover_sessions)."""

    def _fake_session(self, tmp_path: Path) -> SessionMeta:
        file = tmp_path / "fake-session.jsonl"
        file.write_text("", encoding="utf-8")
        return SessionMeta(
            session_id="abcdef1234567890",
            project_path=str(tmp_path),
            file_path=file,
            started_at="2026-04-08T09:00:00Z",
            git_branch="main",
            message_count=5,
            size_bytes=1024,
        )

    def test_calls_pipeline(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_reverse_impl

        fake_session = self._fake_session(tmp_path)
        fake_context = SessionContext(
            session_id="abcdef1234567890",
            git_branch="main",
            files_changed=[],  # len = 0, just for counting
            commands_run=["pytest", "ruff"],
            decisions=["Chose pytest over unittest", "Used FastAPI over Flask"],
            next_steps=["Write docs", "Add integration tests"],
        )

        with (
            patch(
                "handover.parsers.claude_code.ClaudeCodeSessionParser.discover_sessions",
                return_value=[fake_session],
            ),
            patch("handover.reverse.reverse", return_value=fake_context),
            patch(
                "handover.generator.Generator.generate_handover", return_value={"HANDOVER.md": ""}
            ),
        ):
            result = handover_reverse_impl(
                project_dir=str(tmp_path),
                output_dir=str(tmp_path),
                no_llm=True,
            )

        assert "Session: abcdef12" in result
        assert "Branch: main" in result
        assert "Files changed: 0" in result
        assert "Commands run: 2" in result
        assert "Key decisions made:" in result
        assert "Chose pytest over unittest" in result
        assert "Recommended next steps:" in result
        assert "Full summary written to:" in result
        assert "HANDOVER.md" in result

    def test_no_sessions_returns_message(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_reverse_impl

        with patch(
            "handover.parsers.claude_code.ClaudeCodeSessionParser.discover_sessions",
            return_value=[],
        ):
            result = handover_reverse_impl(project_dir=str(tmp_path))
        assert "No Claude Code sessions found" in result
        assert "Run a Claude Code session first" in result

    def test_reverse_exception_surfaces_error(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_reverse_impl

        fake_session = self._fake_session(tmp_path)
        with (
            patch(
                "handover.parsers.claude_code.ClaudeCodeSessionParser.discover_sessions",
                return_value=[fake_session],
            ),
            patch("handover.reverse.reverse", side_effect=ValueError("boom")),
        ):
            result = handover_reverse_impl(project_dir=str(tmp_path))
        assert "Error reading session" in result
        assert "boom" in result

    def test_default_output_is_project_dir(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_reverse_impl

        fake_session = self._fake_session(tmp_path)
        fake_context = SessionContext(session_id="deadbeef" * 2, git_branch="main")

        captured: dict[str, Path] = {}

        def _fake_gen(self, context, output_dir, dry_run=False):  # noqa: ARG001
            captured["output_dir"] = output_dir
            return {"HANDOVER.md": ""}

        with (
            patch(
                "handover.parsers.claude_code.ClaudeCodeSessionParser.discover_sessions",
                return_value=[fake_session],
            ),
            patch("handover.reverse.reverse", return_value=fake_context),
            patch("handover.generator.Generator.generate_handover", new=_fake_gen),
        ):
            handover_reverse_impl(project_dir=str(tmp_path))  # no output_dir

        assert captured["output_dir"] == tmp_path.resolve()


