class TestHandoverStatusTool:
    """Unit tests for handover_status_impl (reads .handover/work/backlog.json)."""

    @staticmethod
    def _write_backlog(project: Path, tasks: list[dict]) -> Path:
        backlog_dir = project / ".handover" / "work"
        backlog_dir.mkdir(parents=True, exist_ok=True)
        data = {
            "schema_version": "1.0",
            "updated_at": "2026-04-09T10:00:00Z",
            "project": "test-project",
            "tasks": tasks,
            "milestones": [],
        }
        path = backlog_dir / "backlog.json"
        path.write_text(json.dumps(data, indent=2), encoding="utf-8")
        return path

    def test_reads_backlog_json(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_status_impl

        self._write_backlog(
            tmp_path,
            [
                {
                    "id": "task-001",
                    "title": "Scaffold FastAPI",
                    "priority": "high",
                    "done": True,
                    "done_at": "2026-04-08T12:00:00Z",
                },
                {
                    "id": "task-002",
                    "title": "Add JWT middleware",
                    "priority": "high",
                    "done": False,
                },
                {"id": "task-003", "title": "Define schema", "priority": "medium", "done": False},
            ],
        )
        result = handover_status_impl(project_dir=str(tmp_path))

        assert "Project: test-project" in result
        assert "Progress: 1/3 tasks complete" in result
        assert "High priority remaining:" in result
        assert "Add JWT middleware" in result
        assert "Next task: Add JWT middleware" in result
        assert "Last completed: Scaffold FastAPI" in result
        assert "2026-04-08" in result

    def test_missing_file_returns_message(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_status_impl

        result = handover_status_impl(project_dir=str(tmp_path))
        assert "No backlog.json found" in result
        assert "Run handover first" in result

    def test_all_done_hides_next_task(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_status_impl

        self._write_backlog(
            tmp_path,
            [
                {
                    "id": "t1",
                    "title": "A",
                    "priority": "high",
                    "done": True,
                    "done_at": "2026-04-01T10:00:00Z",
                },
                {
                    "id": "t2",
                    "title": "B",
                    "priority": "medium",
                    "done": True,
                    "done_at": "2026-04-02T10:00:00Z",
                },
            ],
        )
        result = handover_status_impl(project_dir=str(tmp_path))
        assert "Progress: 2/2 tasks complete" in result
        assert "Next task:" not in result
        assert "Last completed: B" in result

    def test_none_done_shows_next_only(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_status_impl

        self._write_backlog(
            tmp_path,
            [
                {"id": "t1", "title": "First thing", "priority": "medium", "done": False},
                {"id": "t2", "title": "Second thing", "priority": "low", "done": False},
            ],
        )
        result = handover_status_impl(project_dir=str(tmp_path))
        assert "Progress: 0/2 tasks complete" in result
        assert "Next task: First thing" in result
        assert "Last completed:" not in result
        # No high-priority items → no "High priority" block
        assert "High priority remaining:" not in result

    def test_malformed_backlog_json_returns_error(self, tmp_path: Path) -> None:
        from handover.mcp_server import handover_status_impl

        backlog_dir = tmp_path / ".handover" / "work"
        backlog_dir.mkdir(parents=True)
        (backlog_dir / "backlog.json").write_text("{not-json", encoding="utf-8")

        result = handover_status_impl(project_dir=str(tmp_path))
        assert "Error reading" in result


